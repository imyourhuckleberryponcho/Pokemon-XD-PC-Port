"""usum_gen4: the Gen 4 pack's DATA from the player's own Ultra Sun / Ultra Moon dump (the same 107 species as the Battle Revolution pack).

What this does (docs/GEN4_USUM.md, plain words):
  The Gen 4 pack builder (engine/formats/pbr, `pbr_models`) reads Battle Revolution's tables: base stats, learn-sets, evolutions,
  the TM list, the moves, the names. Ultra Sun / Ultra Moon hold the same facts in the Gen 7 layouts. This module reads the
  dump and writes a small folder that looks to the pack builder exactly like those Battle Revolution tables ("gen4 source"):
      common.fsys     members 8 (personal, 52 bytes a species), 9 (evolutions), 29 (the TM list), 30 (moves, 24 bytes), 32 (learn-sets)
      mes_common.fsys   member 1: the names (species, moves, items, abilities) in the Battle Revolution message layout
      models/<name>.pkx the Gen 4 models, converted (usum_models.py)
      plan.tsv, gen4src.txt
  `pbr_models --gen4-source <folder> --xd-disc <XD> --gen4-pack <out>` then makes the pack by the ONE code path the Battle
  Revolution pack uses, so the two packs have the same files, numbers and layout.

Gen 4 numbers (`gen4_values`, default ON, `--gen4-values off` to leave the Gen 7 numbers): Ultra Sun / Ultra Moon hold Gen 7 values.
A few differ from Diamond/Pearl (base experience, two base stats, two types, three catch rates, power / accuracy / PP of about
twenty moves). usum_gen4_values.py / usum_gen4_learnsets.py (generated by gen4_public_data.py from public data) hold the Diamond/Pearl
numbers, learn-sets and machine lists; with the switch off they are Gen 7's.
Nothing from the games is in the repository: everything is read from the player's dump at run time.
"""

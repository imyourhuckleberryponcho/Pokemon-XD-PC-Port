def type7to4(t):
    return t if t < 9 else t + 1 if t <= 16 else None


def evo_method7to4(m):
    if 1 <= m <= 6:
        return m
    if 8 <= m <= 27:
        return m - 1
    return 0


FLAG_BITS = ((0, 0), (3, 1), (4, 2), (5, 3), (6, 4))


def u16(b, o):
    return struct.unpack_from('<H', b, o)[0]


def be16(v):
    return struct.pack('>H', v & 0xFFFF)


def be32(v):
    return struct.pack('>I', v & 0xFFFFFFFF)



class Usum:
    """The data archives of an Ultra Sun / Ultra Moon dump (found by what they hold, as gamedetect does)."""

    def __init__(self, r, prod=''):
        self.r = r
        self.det = gamedetect.detect(r, prod)
        self.pers = gamedetect.archive(r, self.det, 'personal')
        self.level = gamedetect.archive(r, self.det, 'levelup')
        self.evo = self._find_evolutions()
        self.moves = self._find_moves()
        self.text = gamedetect.archive(r, self.det, 'text')
        self._names = self._find_names()

    def _same_folder(self):
        base = self.det['personal'].rsplit('/', 1)[0] + '/'
        return sorted(p for p in self.r.files if p.startswith(base))

    def _find_evolutions(self):
        n = len(self.level.entries)
        for p in self._same_folder():
            if p in (self.det['personal'], self.det['levelup']) or self.r.files[p][1] > 8000000:
                continue
            try:
                g = gamedetect._garc(self.r, p)
                if len(g.entries) == n:
                    d = garc.maybe(g.read(82)) if n > 82 else b''
                    d25 = garc.maybe(g.read(25))
                    if len(d25) == 64 and len(d) == 64 and 26 in [u16(d25, 8 * k + 4) for k in range(8)] and 462 in [u16(d, 8 * k + 4) for k in range(8)]:
                        return g
            except Exception:
                continue
        raise SystemExit('3DS dump: the evolution table was not found')

    def _find_moves(self):
        for p in self._same_folder():
            try:
                g = gamedetect._garc(self.r, p)
                if len(g.entries) == 1 and self.r.files[p][1] > 8000:
                    d = garc.maybe(g.read(0))
                    if d[:2] == b'WD' and u16(d, 2) > 700:
                        return d
            except Exception:
                continue
        raise SystemExit('3DS dump: the move table was not found')

    def _find_names(self):
        """{'species', 'moves', 'abilities', 'items'}: the text entries found by their first lines."""
        want = {'species': ('Bulbasaur', 'Ivysaur', 1), 'moves': ('Pound', 'Karate Chop', 1), 'abilities': ('Stench', 'Drizzle', 1),
                'items': ('Master Ball', 'Ultra Ball', 1)}
        got = {}
        for e in range(len(self.text.entries)):
            try:
                t = gamedetect.decode_text(garc.maybe(self.text.read(e)))
            except Exception:
                continue
            if len(t) < 100:
                continue
            for k, (a, b, i) in want.items():
                if k not in got and len(t) > 2 and t[i] == a and t[i + 1] == b:
                    got[k] = t
        missing = [k for k in want if k not in got]
        if missing:
            raise SystemExit('3DS dump: the English text for %s was not found' % ', '.join(missing))
        return got


    def personal(self, dex):
        return garc.maybe(self.pers.read(dex))

    def learnset(self, dex):
        d = garc.maybe(self.level.read(dex))
        out = []
        for k in range(0, len(d) - 3, 4):
            m, lv = struct.unpack_from('<hh', d, k)
            if m < 0:
                break
            out.append((lv, m))
        return out

    def evolutions(self, dex):
        d = garc.maybe(self.evo.read(dex))
        out = []
        for k in range(8):
            m, p, s, form, lv = struct.unpack_from('<HHHBB', d, 8 * k)
            if m:
                out.append((m, p, s, form, lv))
        return out

    def move_record(self, m):
        n = u16(self.moves, 2)
        offs = struct.unpack_from('<%dI' % (n + 1), self.moves, 4)
        return self.moves[offs[m]:offs[m + 1]]

    def name(self, kind, i):
        t = self._names[kind]
        return t[i] if 0 <= i < len(t) else ''



def tm_bits_gen4(us, dex, learn_moves, public=None):
    """The 100 machine bits of a species as Battle Revolution holds them (bit k = Gen 4 machine k): a machine whose move is a Gen 7 machine
    follows the Gen 7 bits; a Gen 4 machine that Gen 7 no longer has (Dig, Brine, Dragon Pulse...) is set when the species learns the move
    by level up in Gen 7 (the dump has no other record of it)."""
    if public is not None:
        return sum(1 << k for k, mv in enumerate(GEN4_TM) if mv in public)
    d = us.personal(dex)
    g7 = int.from_bytes(d[0x28:0x28 + 16], 'little')
    g7_moves = {}
    for j, nm in enumerate(GEN7_TM_NAMES):
        g7_moves.setdefault(nm, j)
    bits = 0
    for k, mv in enumerate(GEN4_TM):
        nm = us.name('moves', mv)
        if nm in g7_moves:
            on = (g7 >> g7_moves[nm]) & 1
        else:
            on = 1 if mv in learn_moves else 0
        bits |= on << k
    return bits


def personal_record(us, dex, values):
    """One 52-byte Battle Revolution personal record from the dump's 84-byte Gen 7 record."""
    d = us.personal(dex)
    learn = {m for _, m in us.learnset(dex) if 0 < m <= LAST_MOVE}
    r = bytearray(52)
    bits = tm_bits_gen4(us, dex, learn, values.machine_moves(dex) if values is not None else None)
    for w in range(4):
        r[4 * w:4 * w + 4] = be32((bits >> (32 * w)) & 0xFFFFFFFF)
    held = [u16(d, 0x0C), u16(d, 0x0E)]
    if values is not None and values.held_items(dex) is not None:
        held = values.held_items(dex)
    r[16:18], r[18:20] = be16(held[0]), be16(held[1])
    r[20:22] = be16(u16(d, 0x24) // 10)
    r[22:24] = be16(u16(d, 0x26))
    r[30:36] = bytes(d[0:6])
    t1, t2 = type7to4(d[6]), type7to4(d[7])
    r[36], r[37] = t1 if t1 is not None else 0, t2 if t2 is not None else 0
    r[38] = d[8]
    r[39] = min(u16(d, 0x22), 255)
    ev7 = u16(d, 0x0A)
    ev = [(ev7 >> s) & 3 for s in (0, 2, 4, 6, 8, 10)]
    r[40:42] = be16(sum(v << (14 - 2 * k) for k, v in enumerate(ev)))
    r[42], r[43], r[44], r[45] = d[0x12], d[0x13], d[0x14], d[0x15]
    r[46], r[47] = d[0x16], d[0x17]
    r[48], r[49] = d[0x18], d[0x19]
    if values is not None:
        values.apply_personal(dex, r, d)
    return bytes(r)


def evolution_record(us, dex):
    """42 bytes: seven {method, parameter, species} (big-endian), Diamond/Pearl numbering."""
    out = bytearray(42)
    k = 0
    for m, p, s, form, lv in us.evolutions(dex):
        if s > 493 or form not in (0, 255):
            continue
        m4 = evo_method7to4(m)
        if not m4 or k >= 7:
            continue

        if m4 in (4, 8, 9, 10, 22, 23) or (m4 in (11, 12, 13) and p == 0):
            p = lv
        out[6 * k:6 * k + 6] = be16(m4) + be16(p) + be16(s)
        k += 1
    return bytes(out)


def learnset_record(us, dex, values=None):
    """80 bytes: twenty {move, level, 0}; the end is {0, 0, 0xD0}. Gen 7's list without the moves Gen 4 has no number for; the
    evolution moves (level 0) count as level 1; a move twice keeps its earlier level; at most twenty (the latest ones kept)."""
    seen, rows = set(), []
    gen4 = values.levelup(dex) if values is not None else None
    for lv, m in (gen4 if gen4 is not None else us.learnset(dex)):
        if not (0 < m <= LAST_MOVE) or m in seen:
            continue
        seen.add(m)
        rows.append((max(lv, 1), m))
    rows.sort(key=lambda x: x[0])
    rows = rows[-20:]
    out = bytearray(80)
    for k in range(20):
        if k < len(rows):
            out[4 * k:4 * k + 4] = be16(rows[k][1]) + bytes([rows[k][0], 0])
        else:
            out[4 * k:4 * k + 4] = bytes([0, 0, 0, 0xD0])
            break
    return bytes(out)


def move_row(us, m, values, donors, plan_names):
    """24 bytes of Battle Revolution's move table (+0 effect, +14 class, +15 power, +16 type, +17 accuracy, +18 PP, +19 chance,
    +20 priority, +21 flags). The effect number only has to group moves the way the pack builder expects: a Gen 1-3 move is its
    own group (its own number); a Gen 4 move that takes a Gen 1-3 move's effect gets that move's number (usum_gen4_donors.py);
    every other Gen 4 move gets 1000 + its number (a new effect the pack builds by name)."""
    u = us.move_record(m)
    r = bytearray(24)
    name = us.name('moves', m)
    eff = m if m <= 354 else donors.get(name, 1000 + m)
    r[0:2] = be16(eff)
    r[14] = {1: 0, 2: 1, 0: 2}.get(u[2], 2)
    r[15] = u[3]
    t = type7to4(u[0])
    r[16] = t if t is not None else 0
    r[17] = 0 if u[4] >= 101 else u[4]
    r[18] = u[5]
    r[19] = effect_chance(u)
    r[20] = u[6]
    flags = struct.unpack_from('<I', u, 36)[0]
    f = 0
    for src, dst in FLAG_BITS:
        f |= ((flags >> src) & 1) << dst
    r[21] = f
    if values is not None and m > 354:
        values.apply_move(name, r)
    return bytes(r)


def effect_chance(u):
    """The chance of the extra effect in percent, as Battle Revolution lists it: the status chance, else the flinch chance, else a stat
    change's chance (always 100 for a stat drop on the user or an always-hit drop); trapping moves list none."""
    if u[8] == 0 and u[9] == 0 and u[10] and False:
        return 0
    inflict = u[8] | (u[9] << 8)
    if inflict in (8,):
        return 0
    if u[10]:
        return u[10]
    if u[15]:
        return u[15]
    for k in range(3):
        if u[21 + k] and u[27 + k]:
            return u[27 + k]
    return 0



def mesg(strings):
    """Battle Revolution's message file: 'MESG', the count, 0x10-byte header, big-endian offsets, UTF-16BE strings."""
    n = len(strings)
    head = 0x10 + 4 * n
    body = bytearray()
    offs = []
    for s in strings:
        offs.append(head + len(body))
        body += s.encode('utf-16-be') + b'\0\0'
    out = bytearray(head)
    out[0:4] = b'MESG'
    out[4:8] = be32(n)
    for k, o in enumerate(offs):
        out[0x10 + 4 * k:0x14 + 4 * k] = be32(o)
    return bytes(out + body)


def message_table(us):
    """species 9 + dex (capitals), moves 505 + move, items 1990 + item, abilities 2989 + ability."""
    n = 2989 + 124
    t = [''] * n
    for dex in range(1, 501):
        t[9 + dex] = us.name('species', dex).upper()
    for m in range(1, LAST_MOVE + 1):
        t[505 + m] = us.name('moves', m)
    for i in range(1, 960):
        if 1990 + i < 2989:
            t[1990 + i] = us.name('items', i)
    for a in range(1, 124):
        t[2989 + a] = us.name('abilities', a)
    return t



def align(v, n):
    return (v + n - 1) // n * n


def build_fsys(archive_id, entries):
    entries = [e if len(e) == 6 else (e[0], e[1], e[2], e[3], len(e[3]), False) for e in entries]
    n = len(entries)
    table = 0x60
    names_at = align(table + 4 * n, 16)
    names = bytearray()
    name_off = []
    for _, _, name, _, _, _ in entries:
        name_off.append(names_at + len(names))
        names += name.encode('latin1') + b'\0'
    hdrs_at = align(names_at + len(names), 16)
    data_at = align(hdrs_at + 0x70 * n, 32)
    pos = data_at
    offs = []
    for _, _, _, data, _, _ in entries:
        offs.append(pos)
        pos = align(pos + len(data), 32)
    total = pos + 0x20
    out = bytearray(total)
    out[0:4] = b'FSYS'
    struct.pack_into('>8I', out, 4, 0x201, archive_id, n, 0x80000000, 3, 0x40, data_at, total)
    struct.pack_into('>3I', out, 0x40, table, names_at, data_at)
    out[names_at:names_at + len(names)] = names
    for i, (w0, typ, name, data, size, packed) in enumerate(entries):
        h = hdrs_at + 0x70 * i
        struct.pack_into('>I', out, table + 4 * i, h)
        struct.pack_into('>10I', out, h, w0, offs[i], size, 0x80000000 if packed else 0, 0, len(data), 0, 0, typ, name_off[i])
        out[offs[i]:offs[i] + len(data)] = data
    out[total - 4:total] = b'FSYS'
    return bytes(out)


def table_member(rows, header, count_rows):
    """A table member: `header` bytes, then the rows."""
    return bytes(header) + b''.join(rows)



def write_source(us, out, values=None, log=print):
    """Writes common.fsys, mes_common.fsys and gen4src.txt into `out`. `values` = usum_gen4_values.Values or None (Gen 7 numbers)."""
    import usum_gen4_donors
    os.makedirs(out, exist_ok=True)
    pers = [personal_record(us, dex, values) if 1 <= dex <= 493 else bytes(52) for dex in range(SPECIES_TOTAL)]
    pers[0] = bytes(52)
    evos = [evolution_record(us, dex) if 1 <= dex <= 493 else bytes(42) for dex in range(SPECIES_TOTAL)]
    learn = [learnset_record(us, dex, values) if 1 <= dex <= 493 else bytes([0, 0, 0, 0xD0]) + bytes(76) for dex in range(SPECIES_TOTAL)]
    tmlist = b''.join(be16(m) + b'\0\0' for m in GEN4_TM)
    moves = [bytes(24)] + [move_row(us, m, values, usum_gen4_donors.DONOR_OF, None) for m in range(1, LAST_MOVE + 1)]
    members = [(0, 0, 'blank%d' % i, b'') for i in range(33)]

    def put(i, name, data):
        members[i] = (i << 16 | 0x1200, 0, name, data)
    put(8, 'personal', bytes(0x30) + b''.join(pers))
    put(9, 'evolutions', bytes(0x30) + b''.join(evos))
    put(29, 'tm_list', bytes(0x30) + tmlist)
    put(30, 'moves', bytes(0x40) + b''.join(moves))
    put(32, 'learnsets', bytes(0x30) + b''.join(learn))
    open(os.path.join(out, 'common.fsys'), 'wb').write(build_fsys(0x4C1, members))
    mes = [(0, 0, 'blank0', b''), (1 << 16 | 0x1200, 0, 'mes_common', mesg(message_table(us)))]
    open(os.path.join(out, 'mes_common.fsys'), 'wb').write(build_fsys(0x4C2, mes))
    log('gen4 source: %d species, %d moves' % (GEN4_LAST - GEN4_FIRST + 1, LAST_MOVE))



"""Writes engine/formats/n3ds/unicode_upper.inc: Python's str.upper() for every character of the BMP that changes (Unicode facts, no game data).
The C++ data build needs it because XD writes names in capitals the way Python's upper() does (sharp s -> SS ...)."""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(HERE))), 'engine', 'formats', 'n3ds', 'unicode_upper.inc')
rows = []
for c in range(0x80, 0x10000):
    if 0xD800 <= c < 0xE000:
        continue
    u = chr(c).upper()
    if u != chr(c):
        cps = [ord(x) for x in u]
        assert len(cps) <= 3
        rows.append('{0x%04X,{%s}}' % (c, ','.join('0x%04X' % x for x in cps + [0] * (3 - len(cps)))))
text = '// Generated by tools/n3ds/cpp_ref/make_upper.py (Python %s, Unicode %s): do not edit. {character, {its upper-case characters (0 = none)}}\n' % (sys.version.split()[0], __import__('unicodedata').unidata_version)
text += ',\n'.join(rows) + '\n'
open(out, 'w', newline='\n').write(text)
print(len(rows), 'rows', out)

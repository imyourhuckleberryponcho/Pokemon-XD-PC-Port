"""Writes engine/formats/pbr/pbr_pack_rules.cpp from the Python rule files (run from the repo root; the Python is the reference).
   python engine/formats/pbr/tests/gen_rules_cpp.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'pbr_convert'))
import gen4_rules as R, gen4_move_rules as M, gen4_spots as S


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


o = []
o.append('// Rules of the Gen 4 pack as data: gen4_rules.py, gen4_move_rules.py, gen4_spots.py (our own decisions; no game data).')
o.append('// Generated by tests/gen_rules_cpp.py; the Python stays the reference.')
o.append('#include "pbr_pack.h"')
o.append('namespace pbr {')
o.append('const std::vector<std::pair<std::string, std::string>> kMoveSubstitute = {')
for k, v in R.MOVE_SUBSTITUTE.items():
    o.append('    {%s, %s},' % (q(k), q(v or '')))
o.append('};')
o.append('const std::map<int, AbilitySub> kAbilitySubstitute = {')
for k, (n, x) in R.ABILITY_SUBSTITUTE.items():
    o.append('    {%d, {%s, %d}},' % (k, q(n), x))
o.append('};')
o.append('const std::set<std::string> kBabies = {' + ', '.join(q(b) for b in sorted(R.BABIES)) + '};')
o.append('const std::vector<SpotTable> kSpots = {')
for t, (probs, adds, top) in S.SPOTS.items():
    rt = S.ORIGINAL_RATES[t]
    o.append('    {%s, {%d, %d, %d}, {%s}, %d, {%d, %d, %d}},' % (q(t), probs[0], probs[1], probs[2], ', '.join('{%s, %d, %d}' % (q(n), p, ro) for n, p, ro in adds), top, rt[0], rt[1], rt[2]))
o.append('};')
import gen4_pack as P
o.append('const std::map<int, std::string> kCategory = {')
for k, v in P.CATEGORY.items():
    o.append('    {%d, %s},' % (k, q(v)))
o.append('};')
o.append('const std::map<std::string, MovePlanEntry> kMovePlan = {')
for k, (kind, d, note) in M.MOVE_PLAN.items():
    o.append("    {%s, {'%s', %s, %s}}," % (q(k), kind, q(d or ''), q(note)))
o.append('};')
o.append('const std::set<std::string> kPunch = {' + ', '.join(q(b) for b in sorted(M.PUNCH)) + '};')
o.append('const std::set<std::string> kIgnoresProtect = {' + ', '.join(q(b) for b in sorted(M.IGNORES_PROTECT)) + '};')
o.append('const std::map<std::string, int> kChance = {' + ', '.join('{%s, %d}' % (q(k), v) for k, v in M.CHANCE.items()) + '};')
o.append('const std::map<std::string, int> kFixedPower = {' + ', '.join('{%s, %d}' % (q(k), v) for k, v in M.FIXED_POWER.items()) + '};')
o.append('const std::map<std::string, std::string> kAnimDonor = {' + ', '.join('{%s, %s}' % (q(k), q(v)) for k, v in M.ANIM_DONOR.items()) + '};')
o.append('const std::map<std::string, int> kEffectSlots = {' + ', '.join('{%s, %d}' % (q(k), v) for k, v in M.EFFECT_SLOTS.items()) + '};')
o.append('const std::set<std::string> kImplemented = {' + ', '.join(q(b) for b in sorted(M.IMPLEMENTED)) + '};')
o.append('}  // namespace pbr')
open(os.path.join(ROOT, 'engine', 'formats', 'pbr', 'pbr_pack_rules.cpp'), 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
